#!/usr/bin/env python3
# Pack art/out/*.png into src/36_assets.js (palette PNGs as base64).  name -> [density, base64]
# A sprite whose pixels have not changed keeps its old bytes, so a rebuild only touches what you edited.
# Usage: build_assets.py   (then python3 build.py)
from PIL import Image
import glob, os, io, re, base64, numpy as np
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEST = os.path.join(root, 'src/36_assets.js')
ONE = {'o_lamp', 'o_stone'}           # drawn at 1 art px = 1 game px (same as buildings)
def density(n):
    if n.startswith('b_'): return 1
    if n.startswith('h_') and not n.endswith('_hd'): return 1
    if n in ONE: return 1
    return 2
def rgba(im):
    a = np.array(im.convert('RGBA')); a[a[..., 3] < 128] = 0; a[a[..., 3] >= 128, 3] = 255; return a
def pal_png(im):
    a = np.array(im.convert('RGBA')); alpha = a[..., 3] >= 128
    rgb = Image.fromarray(a[..., :3], 'RGB')
    q = rgb.quantize(255, method=Image.MEDIANCUT, dither=Image.NONE)
    idx = np.array(q) + 1; idx[~alpha] = 0
    pal = [0, 0, 0] + q.getpalette()[:255 * 3]
    out = Image.fromarray(idx.astype(np.uint8), 'P'); out.putpalette(pal)
    buf = io.BytesIO(); out.save(buf, 'PNG', optimize=True, transparency=0)
    return buf.getvalue()
old = {}
if os.path.exists(DEST):
    for n, d, b in re.findall(r"^  (\w+): \[(\d), '([A-Za-z0-9+/=]+)'\]", open(DEST).read(), re.M): old[n] = base64.b64decode(b)
items, total, changed = [], 0, []
for f in sorted(glob.glob(os.path.join(root, 'art/out/*.png'))):
    n = os.path.basename(f)[:-4]; im = Image.open(f)
    prev = old.get(n)
    if prev is not None and np.array_equal(rgba(Image.open(io.BytesIO(prev))), rgba(im)): data = prev
    else: data = pal_png(im); changed.append(n)
    total += len(data)
    items.append("  %s: [%d, '%s']" % (n, density(n), base64.b64encode(data).decode()))
open(DEST, 'w').write("// ---- assets ----\n\n// ================= ART ASSETS (generated by tools/build_assets.py from the SpriteCook templates) =================\nconst ASSET_SRC = {\n" + ",\n".join(items) + "\n};")
print(len(items), 'assets,', total, 'bytes png; new or changed:', ', '.join(changed) or 'none')
